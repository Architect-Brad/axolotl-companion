'use strict';
// Generate the TUI part's sprite data from axo-term.js — one source of truth.
const fs = require('fs'), path = require('path');
const A = require('../axo-term.js');

const GLYPH = {
  P: '█', D: '▓', B: '▒', E: '@', W: 'o', M: 'm', T: 't', A: '*', H: '!',
  G: '=', K: '#', k: ':', paper: ' ', green: '+', blue: '~', wood: '|',
  tan: '=', dark: '#', glass: '.', clip: ',', cover: 'x', brown: '|',
};
const hex = (c) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('');
// exact palette lookup + nearest fallback for a few inline RGB literals
const palette = Object.entries(A.C).filter(([, v]) => Array.isArray(v));
const reverse = new Map(palette.map(([k, v]) => [hex(v), k]));
function nearest(c) {
  const h = hex(c); if (reverse.has(h)) return reverse.get(h);
  let best = 'P', bd = Infinity;
  for (const [k, v] of palette) { const d = (v[0]-c[0])**2 + (v[1]-c[1])**2 + (v[2]-c[2])**2; if (d < bd) { bd = d; best = k; } }
  return best;
}

const moods = Object.keys(A.MOODS);
const AXO = {};
for (const mood of moods) {
  const frames = [];
  for (let n = 0; n < 6; n++) {
    const cv = A.frame(mood, n);
    const counts = new Map();
    for (const row of cv) for (const c of row) if (c) { const k = nearest(c); counts.set(k, (counts.get(k) || 0) + 1); }
    const dominant = [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] || 'P';
    const rows = cv.map((row) => row.map((c) => (c ? (GLYPH[nearest(c)] || '█') : ' ')).join('').replace(/\s+$/, ''));
    const colors = cv.map((row) => hex(row.find(Boolean) || A.C.P));
    const f = { rows, colors: colors.map((_, i) => hex([...counts.keys()].length && cv[i].find(Boolean) || A.C.P)) };
    // one fg per row: prefer the dominant sprite color, but keep dark rows dark
    f.colors = cv.map((row) => {
      const keys = row.map((c) => c && nearest(c)).filter(Boolean);
      const dark = keys.filter((k) => ['E', 'M', 'K', 'dark'].includes(k));
      return hex(A.C[dark.length > keys.length / 3 ? 'E' : dominant] || A.C.P);
    });
    if (frames.some((g) => JSON.stringify(g.rows) === JSON.stringify(f.rows))) continue;
    frames.push(f);
  }
  AXO[mood] = frames;
}

const data = JSON.stringify(AXO);
const header = `// GENERATED by tools/gen_tui.js — do not edit. Source: axo-term.js
const AXO = ${data};
`;

const body = `
import { Plugin } from "@opencode/plugin/tui"
import { createSignal, Show } from "solid-js"

const TICK = 250
const QUIET_IDLE = 8_000
const SLEEP_AFTER = 60_000
const BUSY = new Set(["happy", "surprised", "testpass", "testfail", "buildpass", "buildfail"])

export default Plugin.define({
  id: "axolotl.tui",
  setup(context) {
    const [mood, setMood] = createSignal("idle")
    const [tick, setTick] = createSignal(0)
    const [last, setLast] = createSignal(Date.now())
    const [pets, setPets] = createSignal(0)
    const timers = new Set()
    const later = (fn, ms) => {
      const t = setTimeout(() => { timers.delete(t); fn() }, ms)
      timers.add(t); return t
    }
    const react = (m, hold) => {
      setLast(Date.now()); setMood(m)
      if (hold) later(() => setMood("idle"), hold)
    }

    // Server events v2: execution.succeeded/failed, tool.*, session.*
    const stopEvents = context.data.listen(({ details }) => {
      const t = String(details?.type ?? "")
      if (t.includes("execution.succeeded")) return react("happy", 4000)
      if (t.includes("execution.failed") || t.includes("error")) return react("surprised", 2500)
      if (t.includes("tool") || t.startsWith("session.") || t.includes("message")) {
        setLast(Date.now())
        if (mood() === "sleepy" || mood() === "idle") setMood("thinking")
      }
    })

    let n = 0
    const stopClock = setInterval(() => {
      n++; setTick(n)
      if (BUSY.has(mood())) return
      const quiet = Date.now() - last()
      if (quiet > SLEEP_AFTER) setMood("sleepy")
      else if (quiet > QUIET_IDLE) setMood("idle")
      else if (mood() === "idle") setMood("thinking")
    }, TICK)

    const framesFor = (m) => AXO[m] || AXO.idle
    const frame = () => {
      const fs = framesFor(mood())
      return fs[tick() % fs.length]
    }
    const sprite = (f) => (
      <box flexDirection="column">
        {f.rows.map((line, i) => <text fg={f.colors[i]}>{line}</text>)}
      </box>
    )

    context.ui.slot({
      append: "sidebar.footer",
      render: () => sprite(frame()),
    })

    const Axo = () => {
      context.keymap.layer(() => ({
        mode: "global",
        commands: [{
          id: "axolotl.pet.press",
          title: "Pet Axolotl",
          bind: "p",
          run: () => {
            setPets((p) => p + 1); react("happy", 1200)
            context.ui.toast.show({ message: "gill-giggles 🦎", variant: "success", duration: 1500 })
          },
        }],
      }))
      return (
        <box flexDirection="column" paddingLeft={2} paddingTop={1}>
          <text fg="#f4a6b8">AXOLOTL — press p to pet</text>
          {sprite(frame())}
          <text fg="#9a938a">pets: {pets()}</text>
        </box>
      )
    }
    context.ui.slot({
      append: "session.panel",
      render: (panel) => <Show when={panel.name === "axolotl.pet"}><Axo /></Show>,
    })
    context.ui.slot({
      append: "app",
      render: () => {
        context.keymap.layer(() => ({
          mode: "global",
          commands: [{
            id: "axolotl.pet",
            title: "Pet Axolotl",
            group: "Axolotl",
            slash: { name: "pet", aliases: ["axolotl"] },
            run: () => context.ui.panel.open("axolotl.pet"),
          }],
        }))
        return null
      },
    })

    return () => {
      stopEvents(); clearInterval(stopClock)
      for (const t of timers) clearTimeout(t)
    }
  },
})
`;

const out = path.join(__dirname, '..', 'src', 'tui.tsx');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, header + body);
console.log(`wrote ${out} (${(fs.statSync(out).size / 1024).toFixed(1)} KB, ${Object.keys(AXO).length} moods)`);
